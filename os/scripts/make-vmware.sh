#!/usr/bin/env bash
# VMware Workstation 가상머신 패키지: .vmx + 빈 32GB .vmdk + ISO 연결
# VMware 에서 out/vmware/AlliedID-26.11.1/AlliedID.vmx 를 열고 전원을 켜면 라이브 ISO 로 부팅한다.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
. "$ROOT/os/config/os.env"
ISO="AlliedID-$AID_VERSION-desktop-amd64.iso"
VM="$ROOT/out/vmware/AlliedID-$AID_VERSION"
[[ -f "$ROOT/out/$ISO" ]] || { echo "먼저 os/build.sh iso" >&2; exit 1; }
mkdir -p "$VM"
cp -f "$ROOT/out/$ISO" "$VM/$ISO"
[[ -f "$VM/AlliedID.vmdk" ]] || qemu-img create -q -f vmdk -o subformat=monolithicSparse,adapter_type=lsilogic "$VM/AlliedID.vmdk" 32G
cat > "$VM/AlliedID.vmx" <<VMX
.encoding = "UTF-8"
config.version = "8"
virtualHW.version = "19"
displayName = "$AID_PRETTY"
guestOS = "ubuntu-64"
firmware = "efi"
uefi.secureBoot.enabled = "FALSE"
memsize = "4096"
numvcpus = "2"
scsi0.present = "TRUE"
scsi0.virtualDev = "lsilogic"
scsi0:0.present = "TRUE"
scsi0:0.fileName = "AlliedID.vmdk"
sata0.present = "TRUE"
sata0:1.present = "TRUE"
sata0:1.deviceType = "cdrom-image"
sata0:1.fileName = "$ISO"
sata0:1.startConnected = "TRUE"
ethernet0.present = "TRUE"
ethernet0.connectionType = "nat"
ethernet0.virtualDev = "vmxnet3"
ethernet0.addressType = "generated"
usb.present = "TRUE"
ehci.present = "TRUE"
usb_xhci.present = "TRUE"
usb.generic.allowHID = "TRUE"
sound.present = "TRUE"
sound.virtualDev = "hdaudio"
sound.autoDetect = "TRUE"
svga.graphicsMemoryKB = "262144"
mks.enable3d = "TRUE"
tools.syncTime = "TRUE"
VMX
echo "✓ $VM/AlliedID.vmx"
echo "  VMware Workstation → 파일 → 열기 → AlliedID.vmx → 전원 켜기"
echo "  설치: 라이브 세션 터미널에서  sudo alliedid-install /dev/sda"
