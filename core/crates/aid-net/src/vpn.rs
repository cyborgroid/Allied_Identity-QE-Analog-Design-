//! 국경 없는 오버레이 망.
//!
//! 모든 AlliedID 기기는 하나의 WireGuard 오버레이에 참여한다. 기기의 오버레이
//! 주소와 WireGuard 키는 **기기 신원에서 결정적으로 파생**되므로, 번호만 알면
//! 주소를 알 수 있고(국가/통신사 개념 없음), 기기를 바꾸지 않는 한 키가 바뀌지 않는다.
//!
//! * IPv6: `fd26:a11e:d000::/48` + 번호 해시 80비트
//! * IPv4: `100.64.0.0/10` (CGNAT 대역) + 번호 해시 22비트 — 충돌 가능, 보조용

use aid_identity::{AidNumber, DeviceIdentity};
use base64::{engine::general_purpose::STANDARD as B64, Engine};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::net::{Ipv4Addr, Ipv6Addr};
use x25519_dalek::{PublicKey, StaticSecret};

pub const OVERLAY_V6_PREFIX: [u16; 3] = [0xfd26, 0xa11e, 0xd000];
pub const WG_PORT: u16 = 51820;
pub const INTERFACE: &str = "aid0";

fn h(number: &AidNumber) -> [u8; 32] {
    Sha256::digest(format!("alliedid/overlay/v1/{}", number.digits()).as_bytes()).into()
}

pub fn overlay_v6(number: &AidNumber) -> Ipv6Addr {
    let d = h(number);
    let w = |i: usize| u16::from_be_bytes([d[i], d[i + 1]]);
    Ipv6Addr::new(OVERLAY_V6_PREFIX[0], OVERLAY_V6_PREFIX[1], OVERLAY_V6_PREFIX[2], w(0), w(2), w(4), w(6), w(8))
}

pub fn overlay_v4(number: &AidNumber) -> Ipv4Addr {
    let d = h(number);
    let host = u32::from_be_bytes([0, d[10], d[11], d[12]]) & 0x3f_ffff; // 22 bits
    let host = host.clamp(1, 0x3f_fffe);
    Ipv4Addr::from((100u32 << 24) | (64 << 16) | host)
}

pub struct WgKeys {
    pub private_b64: String,
    pub public_b64: String,
}

/// 기기 신원에서 WireGuard 키쌍을 파생.
pub fn wg_keys(id: &DeviceIdentity) -> WgKeys {
    let secret = StaticSecret::from(id.derive_secret("wireguard"));
    let public = PublicKey::from(&secret);
    WgKeys { private_b64: B64.encode(secret.to_bytes()), public_b64: B64.encode(public.as_bytes()) }
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Peer {
    pub number: AidNumber,
    pub wg_public_key: String,
    /// `host:port`. 없으면 상대가 나에게 접속해 오기를 기다린다.
    #[serde(default)]
    pub endpoint: Option<String>,
    /// 릴레이(허브) 피어면 오버레이 전체를 이쪽으로 라우팅
    #[serde(default)]
    pub relay: bool,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct PeerBook {
    pub peers: Vec<Peer>,
}

/// `wg-quick` 형식 설정 생성.
pub fn wg_quick_config(id: &DeviceIdentity, peers: &PeerBook, listen_port: u16) -> String {
    let me = id.number();
    let keys = wg_keys(id);
    let mut s = format!(
        "# AlliedID overlay — {me}\n# generated by `aid vpn config`; do not edit by hand\n[Interface]\nPrivateKey = {}\nAddress = {}/48, {}/10\nListenPort = {listen_port}\n",
        keys.private_b64,
        overlay_v6(&me),
        overlay_v4(&me),
    );
    for p in &peers.peers {
        let allowed = if p.relay {
            "fd26:a11e:d000::/48, 100.64.0.0/10".to_string()
        } else {
            format!("{}/128, {}/32", overlay_v6(&p.number), overlay_v4(&p.number))
        };
        s.push_str(&format!("\n# {}\n[Peer]\nPublicKey = {}\nAllowedIPs = {allowed}\nPersistentKeepalive = 25\n", p.number, p.wg_public_key));
        if let Some(ep) = &p.endpoint {
            s.push_str(&format!("Endpoint = {ep}\n"));
        }
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn overlay_addresses_are_deterministic_and_in_range() {
        let n = AidNumber::from_public_key(&ed25519_dalek::SigningKey::from_bytes(&[9u8; 32]).verifying_key());
        assert_eq!(overlay_v6(&n), overlay_v6(&n));
        assert_eq!(overlay_v6(&n).segments()[..3], OVERLAY_V6_PREFIX);
        let o = overlay_v4(&n).octets();
        assert_eq!(o[0], 100);
        assert!((64..128).contains(&o[1]));
    }
}
